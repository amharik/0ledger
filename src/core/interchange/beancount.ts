const TALLY_PARENT_BY_ACCOUNT_PREFIX: [RegExp, string][] = [
  [/^Assets:Cash\b/, 'Cash-in-Hand'],
  [/^Assets:Bank\b/, 'Bank Accounts'],
  [/^Assets:(?:Receivable|Sundry-Debtors)\b/, 'Sundry Debtors'],
  [/^Assets:Stock\b/, 'Stock-in-Hand'],
  [/^Assets:/, 'Current Assets'],
  [/^Liabilities:(?:Payable|Sundry-Creditors)\b/, 'Sundry Creditors'],
  [/^Liabilities:Tax/, 'Duties & Taxes'],
  [/^Liabilities:/, 'Current Liabilities'],
  [/^Equity:/, 'Capital Account'],
  [/^Income:Sales\b/, 'Sales Accounts'],
  [/^Income:/, 'Indirect Income'],
  [/^Expenses:Purchase\b/, 'Purchase Accounts'],
  [/^Expenses:/, 'Indirect Expenses'],
];

function accountComponent(value: string, fallback = 'Account'): string {
  const slug = slugify(value, fallback).slice(0, 40);
  if (slug.length === 0) return fallback;
  return slug
    .split('-')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('-');
}

function accountRoot(ledger: Ledger): string {
  return ROOT_BY_TALLY_PARENT[ledger.tallyParent] ?? 'Assets';
}

export function ledgerAccountName(
  ledger: Ledger,
  used = new Map<string, string>(),
): string {
  const component = accountComponent(ledger.readableName ?? ledger.name);
  const root = accountRoot(ledger);
  const base =
    ledger.tallyParent === 'Sundry Debtors'
      ? `Assets:Receivable:${component}`
      : ledger.tallyParent === 'Sundry Creditors'
        ? `Liabilities:Payable:${component}`
        : ledger.tallyParent === 'Bank Accounts'
          ? `Assets:Bank:${component}`
          : ledger.tallyParent === 'Cash-in-Hand'
            ? `Assets:Cash:${component}`
            : `${root}:${component}`;
  const existing = used.get(base);
  if (!existing || existing === ledger.id) {
    used.set(base, ledger.id);
    return base;
  }
  const unique = `${base}-${slugify(ledger.id).slice(-6)}`;
  used.set(unique, ledger.id);
  return unique;
}

function quote(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

export interface BeancountExportOptions {
  includeCancelled?: boolean;
}

export function exportBeancount(
  data: WorkbookData,
  options: BeancountExportOptions = {},
): string {
  const accountByLedger = new Map<string, string>();
  const used = new Map<string, string>();
  for (const ledger of data.ledgers) {
    accountByLedger.set(ledger.id, ledgerAccountName(ledger, used));
  }
  const ledgerById = new Map(data.ledgers.map((ledger) => [ledger.id, ledger]));
  const linesByVoucher = new Map<string, typeof data.voucherLines>();
  for (const line of data.voucherLines) {
    const list = linesByVoucher.get(line.voucherId) ?? [];
    list.push(line);
    linesByVoucher.set(line.voucherId, list);
  }
  const vouchers = data.vouchers
    .filter((voucher) => options.includeCancelled || voucher.status === 'regular')
    .sort((a, b) => a.date.localeCompare(b.date) || a.number.localeCompare(b.number));

  const output: string[] = [
    `option "title" ${quote(data.company.legalName)}`,
    `option "operating_currency" ${quote(data.company.currency)}`,
    `; Generated by 0ledger for workspace ${data.workspace.name} (${data.workspace.slug})`,
    '',
  ];

  for (const voucher of vouchers) {
    const party = voucher.partyLedgerId ? ledgerById.get(voucher.partyLedgerId) : undefined;
    const payee = party?.name ?? data.company.legalName;
    const narration = voucher.narration ?? `${voucher.voucherType} ${voucher.number}`;
    output.push(`${voucher.date} * ${quote(payee)} ${quote(narration)}`);
    output.push(`  voucher-id: ${quote(voucher.id)}`);
    output.push(`  voucher-type: ${quote(voucher.voucherType)}`);
    output.push(`  number: ${quote(voucher.number)}`);
    output.push(`  status: ${quote(voucher.status)}`);
    if (voucher.partyLedgerId) output.push(`  party-id: ${quote(voucher.partyLedgerId)}`);
    if (voucher.invoiceNumber) output.push(`  invoice: ${quote(voucher.invoiceNumber)}`);
    if (voucher.reference) output.push(`  reference: ${quote(voucher.reference)}`);
    if (voucher.sourceRef) output.push(`  source-ref: ${quote(voucher.sourceRef)}`);
    for (const line of (linesByVoucher.get(voucher.id) ?? []).sort((a, b) => a.lineNo - b.lineNo)) {
      const account = accountByLedger.get(line.ledgerId) ?? `Expenses:${accountComponent(line.ledgerId)}`;
      output.push(`  ${account}  ${minorToDecimalString(line.amountMinor, line.currency)} ${line.currency}`);
      output.push(`    ledger-id: ${quote(line.ledgerId)}`);
      output.push(`    ledger-name: ${quote(ledgerById.get(line.ledgerId)?.name ?? line.ledgerId)}`);
      if (line.narration) output.push(`    narration: ${quote(line.narration)}`);
    }
    output.push('');
  }
  return output.join('\n');
}

interface ParsedPosting {
  account: string;
  amountMinor: number;
  currency: string;
  ledgerId?: string;
  ledgerName?: string;
  narration?: string;
}

interface ParsedBeancountTransaction {
  line: number;
  date: string;
  payee?: string;
  narration: string;
  meta: Record<string, string>;
  postings: ParsedPosting[];
}

function unquote(value: string): string {
  const trimmed = value.trim();
  if (!trimmed.startsWith('"')) return trimmed;
  return trimmed
    .replace(/^"|"$/g, '')
    .replace(/\\n/g, '\n')
    .replace(/\\"/g, '"')
    .replace(/\\\\/g, '\\');
}

function parseHeaderStrings(rest: string): { payee?: string; narration: string } {
  const strings = [...rest.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((match) => unquote(match[0]!));
  if (strings.length >= 2) return { payee: strings[0]!, narration: strings[1] ?? '' };
  return { narration: strings[0] ?? rest.trim() };
}

export function parseBeancount(text: string): ParsedBeancountTransaction[] {
  const lines = text.split(/\r?\n/);
  const transactions: ParsedBeancountTransaction[] = [];
  let current: ParsedBeancountTransaction | undefined;
  let currentPosting: ParsedPosting | undefined;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index]!;
    if (/^\s*$/.test(line) || /^\s*;/.test(line)) continue;
    const start = /^(\d{4}-\d{2}-\d{2})\s+[*!]\s*(.*)$/.exec(line);
    if (start) {
      if (current) transactions.push(current);
      const header = parseHeaderStrings(start[2]!);
      current = {
        line: index + 1,
        date: start[1]!,
        ...(header.payee ? { payee: header.payee } : {}),
        narration: header.narration,
        meta: {},
        postings: [],
      };
      currentPosting = undefined;
      continue;
    }
    if (!current) continue;
    if (!/^\s+/.test(line)) {
      transactions.push(current);
      current = undefined;
      currentPosting = undefined;
      continue;
    }

    const indent = line.length - line.trimStart().length;
    const content = line.trim();
    const metadata = /^([A-Za-z0-9_-]+):(?:\s+(.*))?$/.exec(content);
    if (metadata) {
      const value = unquote(metadata[2] ?? '');
      if (indent >= 4 && currentPosting) {
        if (metadata[1] === 'ledger-id') currentPosting.ledgerId = value;
        if (metadata[1] === 'ledger-name') currentPosting.ledgerName = value;
        if (metadata[1] === 'narration') currentPosting.narration = value;
      } else {
        current.meta[metadata[1]!] = value;
      }
      continue;
    }

    const posting = /^([A-Za-z][A-Za-z0-9:-]*)\s+(-?[\d,.]+)\s+([A-Z][A-Z0-9]{2,4})$/.exec(content);
    if (!posting) continue;
    currentPosting = {
      account: posting[1]!,
      amountMinor: parseAmountToMinor(posting[2]!.replace(/,/g, ''), posting[3]!),
      currency: posting[3]!,
    };
    current.postings.push(currentPosting);
  }
  if (current) transactions.push(current);
  return transactions;
}

function tallyParentForAccount(account: string): string {
  for (const [pattern, parent] of TALLY_PARENT_BY_ACCOUNT_PREFIX) {
    if (pattern.test(account)) return parent;
  }
  return 'Suspense Account';
}

function ledgerNameForAccount(account: string): string {
  const parts = account.split(':');
  const last = parts.at(-1) ?? 'Account';
  return last.replace(/-/g, ' ').trim() || 'Account';
}

function isVoucherType(value: string | undefined): value is VoucherType {
  return value !== undefined && (VOUCHER_TYPES as readonly string[]).includes(value);
}

export interface BeancountImportResult {
  imported: number;
  skipped: number;
  errors: { line: number; message: string }[];
  warnings: string[];
}

export async function importBeancount(
  db: LedgerDatabase,
  workspaceId: string,
  text: string,
): Promise<BeancountImportResult> {
  const transactions = parseBeancount(text);
  const result: BeancountImportResult = { imported: 0, skipped: 0, errors: [], warnings: [] };
  const workspace = await db.workspaces.get(workspaceId);
  if (!workspace) throw new Error(`Workspace not found: ${workspaceId}`);

  const ledgers = await db.ledgers.where('workspaceId').equals(workspaceId).toArray();
  const ledgerById = new Map(ledgers.map((ledger) => [ledger.id, ledger]));
  const ledgerByName = new Map(ledgers.map((ledger) => [ledger.name.trim().toLocaleLowerCase(), ledger]));
  const accountToLedger = new Map<string, Ledger>();
  for (const ledger of ledgers) accountToLedger.set(ledgerAccountName(ledger), ledger);

  const existing = await db.vouchers.where('workspaceId').equals(workspaceId).toArray();
  const sourceRefs = new Set(existing.flatMap((voucher) => (voucher.sourceRef ? [voucher.sourceRef] : [])));
  const numberKeys = new Set(existing.map((voucher) => `${voucher.voucherType}|${voucher.date}|${voucher.number}`));

  async function resolveLedger(posting: ParsedPosting): Promise<Ledger> {
    if (posting.ledgerId && ledgerById.has(posting.ledgerId)) {
      return ledgerById.get(posting.ledgerId)!;
    }
    const byAccount = accountToLedger.get(posting.account);
    if (byAccount) return byAccount;
    const name = posting.ledgerName?.trim() || ledgerNameForAccount(posting.account);
    const byName = ledgerByName.get(name.toLocaleLowerCase());
    if (byName) {
      accountToLedger.set(posting.account, byName);
      return byName;
    }
    const tallyParent = tallyParentForAccount(posting.account);
    const created = await createLedger(db, {
      workspaceId,
      name,
      tallyParent,
      currency: posting.currency,
    });
    ledgerById.set(created.ledger.id, created.ledger);
    ledgerByName.set(name.toLocaleLowerCase(), created.ledger);
    accountToLedger.set(posting.account, created.ledger);
    return created.ledger;
  }

  for (const transaction of transactions) {
    if (transaction.postings.length < 2) {
      result.errors.push({ line: transaction.line, message: 'Transaction has fewer than two postings' });
      continue;
    }
    try {
      const ref = transaction.meta['source-ref'] ?? `beancount:${await sha256Hex(
        JSON.stringify({
          date: transaction.date,
          payee: transaction.payee,
          narration: transaction.narration,
          postings: transaction.postings.map((posting) => [posting.account, posting.amountMinor]),
        }),
      )}`;
      if (sourceRefs.has(ref)) {
        result.skipped += 1;
        continue;
      }
      const submittedNumber = transaction.meta.number?.trim();
      const voucherType = isVoucherType(transaction.meta['voucher-type'])
        ? transaction.meta['voucher-type']
        : 'Journal';
      if (
        submittedNumber &&
        numberKeys.has(`${voucherType}|${transaction.date}|${submittedNumber}`)
      ) {
        result.skipped += 1;
        continue;
      }

      const lines: {
        ledgerId: string;
        amountMinor: number;
        currency: string;
        narration?: string;
      }[] = [];
      for (const posting of transaction.postings) {
        const ledger = await resolveLedger(posting);
        lines.push({
          ledgerId: ledger.id,
          amountMinor: posting.amountMinor,
          currency: posting.currency,
          ...(posting.narration ? { narration: posting.narration } : {}),
        });
      }
      const partyLedgerId =
        transaction.meta['party-id'] && ledgerById.has(transaction.meta['party-id'])
          ? transaction.meta['party-id']
          : transaction.postings
              .map((posting) => accountToLedger.get(posting.account))
              .find((ledger): ledger is Ledger => ledger?.isParty === true)?.id;
      const status = transaction.meta.status;
      const base: NewVoucherInput = {
        workspaceId,
        voucherType,
        date: transaction.date,
        ...(submittedNumber ? { number: submittedNumber } : {}),
        ...(partyLedgerId ? { partyLedgerId } : {}),
        ...(transaction.meta.invoice ? { invoiceNumber: transaction.meta.invoice } : {}),
        ...(transaction.meta.reference ? { reference: transaction.meta.reference } : {}),
        narration: transaction.narration,
        source: 'import' as const,
        sourceRef: ref,
        ...(status === 'optional' || status === 'cancelled' ? { status } : {}),
        lines,
      };
      try {
        await postVoucher(db, base);
      } catch (error) {
        if (!submittedNumber) throw error;
        delete (base as { number?: string }).number;
        await postVoucher(db, base);
        result.warnings.push(
          `Line ${transaction.line}: kept Tally number ${submittedNumber} in reference because the local numbering scheme rejected it`,
        );
      }
      sourceRefs.add(ref);
      result.imported += 1;
    } catch (error) {
      result.errors.push({
        line: transaction.line,
        message: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return result;
}
